    modified = False
    for bad, good in replacements.items():
        if bad in text:
            text = text.replace(bad, good)
            modified = True
            print(f'Replaced bad string in {path}')
    if modified:
        path.write_text(text, encoding='utf-8')
    else:
        path.write_text(text, encoding='utf-8')
